def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if any output is stale; write nothing")
    args = ap.parse_args()

    try:
        model = load(SCHEMA)
        cases = golden_cases(model)
    except SchemaError as e:
        print(f"host_protocol.toml: {e}", file=sys.stderr)
        return 2

    outputs = {
        OUT_C_HEADER: gen_c_header(model),
        OUT_C_GOLDEN: gen_c_golden(model, cases),
        OUT_TS: gen_ts(model),
        OUT_JSON: gen_json(model, cases),
    }

    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")

    for path in stale:
        verb = "stale" if args.check else "wrote"
        print(f"{verb}: {path.relative_to(ROOT)}")
    if args.check and stale:
        print("run: python3 protocol/gen_protocol.py", file=sys.stderr)
        return 1
    if not stale:
        print("protocol outputs up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
