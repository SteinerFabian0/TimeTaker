def ts_type(f: Field) -> str:
    if f.kind == "scalar":
        t = "bigint" if SCALARS[f.base][0] == 8 else "number"
    elif f.kind == "bytes":
        return "Uint8Array"
    elif f.kind == "str":
        return "string"
    else:
        t = f.struct.name
    return f"{t}[]" if f.tail else t


def ts_field_desc(f: Field) -> str:
    if f.tail:
        if f.kind == "scalar":
            item = f"{{ kind: 'scalar', type: '{f.base}' }}"
        elif f.kind in ("bytes", "str"):
            item = f"{{ kind: '{f.kind}' }}"
        else:
            item = f"{{ kind: 'struct', struct: {f.struct.ts_const} }}"
        return f"{{ name: '{f.name}', kind: 'tail', item: {item} }}"
    if f.kind == "scalar":
        return f"{{ name: '{f.name}', kind: 'scalar', type: '{f.base}' }}"
    if f.kind in ("bytes", "str"):
        return f"{{ name: '{f.name}', kind: '{f.kind}', size: {f.count} }}"
    return f"{{ name: '{f.name}', kind: 'struct', struct: {f.struct.ts_const} }}"


def ts_doc(f: Field) -> str:
    parts = []
    if f.enum:
        parts.append(f"enum {cap_first(f.enum)}")
    if f.doc:
        parts.append(f.doc)
    return f"  /** {'. '.join(parts)} */\n" if parts else ""


def ts_struct(st: Struct, doc: str) -> list[str]:
    o = []
    if doc:
        o.append(f"/** {doc} */")
    o.append(f"export const {st.ts_const}: StructDesc = {{")
    o.append(f"  name: '{st.name}',")
    o.append(f"  size: {st.size},")
    if st.fields:
        o.append("  fields: [")
        o += [f"    {ts_field_desc(f)}," for f in st.fields]
        o.append("  ],")
    else:
        o.append("  fields: [],")
    o.append("};")
    if st.fields:
        o.append(f"export type {st.name} = {{")
        for f in st.fields:
            o.append(f"{ts_doc(f)}  {f.name}: {ts_type(f)};")
        o.append("};")
    else:
        o.append(f"export type {st.name} = Record<string, never>;")
    o.append(f"export const encode{st.name} = (v: {st.name}): Uint8Array => encodeStruct({st.ts_const}, v);")
    o.append(f"export const decode{st.name} = (b: Uint8Array): {st.name} => decodeStruct({st.ts_const}, b) as {st.name};")
    o.append("")
    return o


def ts_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def gen_ts(model: dict) -> str:
    p = model["proto"]
    o = [
        "/*",
        f" * {BANNER}",
        " *",
        " * The TimeTaker host protocol for the web app: constants, struct descriptors,",
        " * types and typed encode/decode wrappers. The encoding itself lives in wire.ts,",
        " * the framing in codec.ts. Format and rules: protocol/host_protocol.toml.",
        " *",
        " * Responses start with `status`. When status !== Status.OK the payload is the",
        " * status alone: check it with responseStatus() before decoding the body.",
        " */",
        "",
        "import { decodeStruct, encodeStruct } from './wire.ts';",
        "import type { StructDesc } from './wire.ts';",
        "",
        f"export const PROTO = {{ major: {p['major']}, minor: {p['minor']}, "
        f"maxPayload: {p['max_payload']}, headerBytes: {HEADER_BYTES} }} as const;",
        "",
        "/** USB identity of the control module (app) and its bootloader: the Web Serial port filter. */",
        f"export const USB_ID = {{ vendorId: 0x{model['usb']['vid']:04x}, productId: 0x{model['usb']['pid']:04x}, "
        f"product: {ts_str(model['usb']['product'])}, productIdBoot: 0x{model['usb']['pid_boot']:04x}, "
        f"productBoot: {ts_str(model['usb']['product_boot'])} }} as const;",
        "",
        "export const HeaderFlag = {",
    ]
    for f in model["flags"]:
        o.append(f"  {f['name']}: 0x{1 << f['bit']:02x},")
    o += ["} as const;", "", "/** ctrlStatus_e: 0 = OK, errors negative. Values are stable. */",
          "export const Status = {"]
    for s in model["statuses"]:
        o.append(f"  {s['name']}: {s['value']},")
    o += ["} as const;", "export type Status = (typeof Status)[keyof typeof Status];", "",
          "const STATUS_NAMES: ReadonlyMap<number, string> = new Map(",
          "  Object.entries(Status).map(([name, code]) => [code, name] as const),",
          ");", "",
          "export function statusName(code: number): string {",
          "  return STATUS_NAMES.get(code) ?? `STATUS_${code}`;",
          "}", "",
          "/** First field of every response payload. */",
          "export function responseStatus(payload: Uint8Array): number {",
          "  if (payload.length < 2) return Status.ERR_BAD_LENGTH;",
          "  return new DataView(payload.buffer, payload.byteOffset, 2).getInt16(0, true);",
          "}", ""]
    for e in model["enums"].values():
        tname = cap_first(e["name"])
        if e.get("doc"):
            o.append(f"/** {e['doc']} */")
        o.append(f"export const {tname} = {{")
        for v in e["values"]:
            val = f"0x{v['value']:02x}" if "Flag" in e["name"] else str(v["value"])
            o.append(f"  {v['name']}: {val},")
        o += ["} as const;", f"export type {tname} = (typeof {tname})[keyof typeof {tname}];", ""]

    o += ["// ---- structs --------------------------------------------------------------", ""]
    o += ts_struct(model["header"], "Frame header, the first 4 bytes of every frame")
    for st in model["structs"].values():
        o += ts_struct(st, st.doc)

    o += ["// ---- messages -------------------------------------------------------------", "",
          "export const MsgId = {"]
    for m in model["messages"]:
        o.append(f"  {m.name}: 0x{m.id:02x},")
    o += ["} as const;", "export type MsgId = (typeof MsgId)[keyof typeof MsgId];", ""]
    for m in model["messages"]:
        o.append(f"// 0x{m.id:02x} {m.name} ({m.kind}): {m.doc}")
        for st, label in ((m.req, "request"), (m.rsp, "response"), (m.body, "")):
            if st is not None:
                o += ts_struct(st, f"{m.name} {label}".strip())

    o += ["export type MsgKind = 'request' | 'event' | 'stream';", "",
          "export interface MsgDesc {",
          "  readonly id: number;",
          "  readonly name: string;",
          "  readonly kind: MsgKind;",
          "  /** Requests: payload host → device. */",
          "  readonly req?: StructDesc;",
          "  /** Requests: response payload (starts with status). */",
          "  readonly rsp?: StructDesc;",
          "  /** Events and streams: payload. */",
          "  readonly body?: StructDesc;",
          "}", "",
          "export const MESSAGES: readonly MsgDesc[] = ["]
    for m in model["messages"]:
        if m.kind == "request":
            parts = f"req: {m.req.ts_const}, rsp: {m.rsp.ts_const}"
        else:
            parts = f"body: {m.body.ts_const}"
        o.append(f"  {{ id: 0x{m.id:02x}, name: {ts_str(m.name)}, kind: '{m.kind}', {parts} }},")
    o += ["];", "",
          "export const MESSAGE_BY_ID: ReadonlyMap<number, MsgDesc> = new Map(MESSAGES.map((m) => [m.id, m]));",
          "", "/** Every struct descriptor by type name (debug console, golden tests). */",
          "export const STRUCTS: Readonly<Record<string, StructDesc>> = {"]
    all_structs = [model["header"], *model["structs"].values()]
    for m in model["messages"]:
        all_structs += [s for s in (m.req, m.rsp, m.body) if s is not None]
    for st in all_structs:
        o.append(f"  {st.name}: {st.ts_const},")
    o += ["};", ""]
    return "\n".join(o)


