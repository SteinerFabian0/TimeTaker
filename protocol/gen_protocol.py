CODEC_VECTORS = [
    ("crc_check_123456789", b"123456789"),
    ("single_byte", b"\x11"),
    ("single_zero", b"\x00"),
    ("two_zeros", b"\x00\x00"),
    ("zeros_at_both_ends", b"\x00\x11\x00\x00\x22\x33\x00"),
    ("max_raw_nonzero_250", bytes(range(1, 251))),
    ("max_raw_all_zero_250", bytes(250)),
    ("block_boundary_253", bytes((i % 255) + 1 for i in range(253))),
]


def golden_cases(model: dict) -> list[dict]:
    flags = {f["name"]: 1 << f["bit"] for f in model["flags"]}
    cases = []
    for m in model["messages"]:
        for part, value in m.examples.items():
            if part == "request":
                st, hflags, tag = m.req, 0, 0x1000 + m.id
            elif part == "response":
                st, hflags, tag = m.rsp, flags["RESPONSE"], 0x1000 + m.id
            else:
                st, tag = m.body, 0
                hflags = flags["EVENT"] if m.kind == "event" else flags["STREAM"]
            where = f"message {m.name} example {part}"
            payload = pack_struct(st, value, where)
            if len(payload) > model["proto"]["max_payload"]:
                raise SchemaError(f"{where}: payload over max_payload")
            header = bytes((m.id, hflags)) + tag.to_bytes(2, "little")
            cases.append({
                "name": f"{m.name} {part}",
                "cname": camel(m.name) + ("" if part == "body" else cap_first(part)),
                "msg": m, "part": part, "struct": st, "value": with_defaults(st, value),
                "header": {"msgId": m.id, "flags": hflags, "tag": tag},
                "payload": payload, "wire": frame_encode(header + payload),
            })
    return cases


# ---------------------------------------------------------------------------
# C output
# ---------------------------------------------------------------------------

def c_comment(text: str) -> str:
    return f" /* {text} */" if text else ""


def c_field_decl(f: Field) -> tuple[str, str, str]:
    enum_note = f"hp{cap_first(f.enum)}_e" if f.enum else ""
    doc = "; ".join(x for x in (enum_note, f.doc) if x)
    if f.tail:
        doc = "; ".join(x for x in ("tail: rest of the payload", doc) if x)
    arr = "[]" if f.tail else (f"[{f.count}]" if f.count is not None else "")
    if f.kind == "scalar":
        ctype = SCALARS[f.base][2]
    elif f.kind == "bytes":
        ctype = "uint8_t"
    elif f.kind == "str":
        ctype = "char"
        doc = "; ".join(x for x in ("UTF-8, zero-padded, not always terminated" if not f.tail
                                     else "UTF-8, no terminator", doc) if x)
    else:
        ctype = f.struct.c_type
    return ctype, f"{f.name}{arr};", doc


def c_struct(st: Struct, doc: str) -> list[str]:
    out = []
    if doc:
        out.append(f"/* {doc} */")
    out.append("typedef struct __attribute__((packed)) {")
    decls = [c_field_decl(f) for f in st.fields]
    tw = max(len(t) for t, _, _ in decls)
    nw = max(len(n) for _, n, _ in decls)
    for t, n, note in decls:
        out.append(f"    {t.ljust(tw)} {n.ljust(nw)}{c_comment(note)}".rstrip())
    out.append(f"}} {st.c_type};")
    out.append(f'_Static_assert(sizeof({st.c_type}) == {st.size}U, "{st.c_type} layout");')
    out.append(f"#define {st.macro}_BYTES {st.size}U")
    if st.tail is not None:
        out.append(f"#define {st.macro}_ITEM_BYTES {st.tail.item_size}U")
        out.append(f"#define {st.macro}_MAX_ITEMS ((HP_MAX_PAYLOAD - {st.macro}_BYTES) / {st.macro}_ITEM_BYTES)")
    out.append("")
    return out


def gen_c_header(model: dict) -> str:
    p = model["proto"]
    o = [
        "/*",
        " * host_protocol.h",
        " *",
        f" * {BANNER}",
        " *",
        " * The TimeTaker host protocol: the same frames over USB CDC and over BLE (via",
        " * the nRF bridge). The wire format and the rules are documented at the top of",
        " * host_protocol.toml, and the design in SYSTEM_ARCHITECTURE.md §7.",
        " *",
        " *   frame    = COBS( header | payload | crc16 LE ) 0x00   (frame_codec.h)",
        " *   response = int16_t status first; on error the payload is the status only",
        " *   event    = uint32_t evSeq first; sequenced, logged, replayable",
        " *",
        " * All structs are packed and little-endian. Read multi-byte fields through the",
        " * struct type (the compiler then emits unaligned-safe loads); never take the",
        " * address of a member.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "_Static_assert(__BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__,",
        '               "host protocol structs assume a little-endian target");',
        "",
        f"#define HP_PROTO_MAJOR      {p['major']}U",
        f"#define HP_PROTO_MINOR      {p['minor']}U",
        f"#define HP_MAX_PAYLOAD      {p['max_payload']}U",
        f"#define HP_MAX_FRAME_RAW    ({HEADER_BYTES}U + HP_MAX_PAYLOAD)  /* header + payload, before CRC and COBS */",
        "",
        f"#define HP_USB_VID          0x{model['usb']['vid']:04X}U  /* USB identity: see [usb] in the TOML */",
        f"#define HP_USB_PID          0x{model['usb']['pid']:04X}U",
        f'#define HP_USB_PRODUCT      "{model["usb"]["product"]}"',
        f"#define HP_USB_PID_BOOT     0x{model['usb']['pid_boot']:04X}U  /* the control bootloader */",
        f'#define HP_USB_PRODUCT_BOOT "{model["usb"]["product_boot"]}"',
        "",
        "/* Header flags */",
    ]
    for f in model["flags"]:
        o.append(f"#define HP_FLAG_{f['name']:<10} 0x{1 << f['bit']:02X}U{c_comment(f.get('doc', ''))}")
    o += ["", "/* =========================================================================",
          " *                       STATUS CODES (ctrlStatus_e)",
          " *",
          " * 0 = OK, errors negative, grouped in tens with gaps. Values are stable across",
          " * versions. ctrl_status.h adds the CTRL_ASSERT* macros on top.",
          " * ========================================================================= */",
          "", "typedef enum {"]
    width = max(len(s["name"]) for s in model["statuses"]) + 5
    for s in model["statuses"]:
        o.append(f"    {('CTRL_' + s['name']).ljust(width)} = {s['value']:>4},{c_comment(s.get('doc', ''))}")
    o += ["} ctrlStatus_e;", "",
          "/* =========================================================================",
          " *                                 ENUMS",
          " * Struct fields stay fixed-width integers; these name their values.",
          " * ========================================================================= */", ""]
    for e in model["enums"].values():
        if e.get("doc"):
            o.append(f"/* {e['doc']} */")
        o.append("typedef enum {")
        width = max(len(v["name"]) for v in e["values"]) + len(e["prefix"]) + 4
        for v in e["values"]:
            name = f"HP_{e['prefix']}_{v['name']}"
            val = f"0x{v['value']:02X}" if "Flag" in e["name"] else str(v["value"])
            o.append(f"    {name.ljust(width)} = {val},{c_comment(v.get('doc', ''))}")
        o += [f"}} hp{cap_first(e['name'])}_e;", ""]

    o += ["/* =========================================================================",
          " *                                STRUCTS",
          " * ========================================================================= */", ""]
    o += c_struct(model["header"], "Frame header, the first 4 bytes of every frame")
    for st in model["structs"].values():
        o += c_struct(st, st.doc)

    o += ["/* =========================================================================",
          " *                               MESSAGES",
          " * ========================================================================= */", ""]
    for m in model["messages"]:
        o.append(f"#define HP_MSG_{m.name:<16} 0x{m.id:02X}U  /* {m.kind} */")
    o.append("")
    for m in model["messages"]:
        o.append(f"/* ---- 0x{m.id:02X} {m.name} ({m.kind}) " + "-" * max(0, 52 - len(m.name) - len(m.kind)))
        if m.doc:
            o.append(f" * {m.doc}")
        o += [" */", ""]
        for st, label in ((m.req, "request"), (m.rsp, "response"), (m.body, "")):
            if st is None:
                continue
            if not st.fields:
                o += [f"/* {m.name} {label}: empty payload */", f"#define {st.macro}_BYTES 0U", ""]
                continue
            o += c_struct(st, f"{m.name} {label}".strip())

    o += ["/* =========================================================================",
          " *                             NAME HELPERS",
          " * For logs and the debugger. Unused ones cost nothing (static inline).",
          " * ========================================================================= */", "",
          "static inline const char *hpMsgName(uint8_t msgId)", "{", "    switch (msgId) {"]
    for m in model["messages"]:
        o.append(f'    case HP_MSG_{m.name}: return "{m.name}";')
    o += ["    default: return \"?\";", "    }", "}", "",
          "static inline const char *ctrlStatusName(int32_t status)", "{", "    switch (status) {"]
    for s in model["statuses"]:
        o.append(f'    case CTRL_{s["name"]}: return "{s["name"]}";')
    o += ["    default: return \"?\";", "    }", "}", ""]
    return "\n".join(o)


def c_int(base: str, v: int) -> str:
    size, signed, _ = SCALARS[base]
    if size == 8:
        return f"{'INT64_C' if signed else 'UINT64_C'}({v})"
    return str(v) if signed else f"{v}U"


def c_byte_list(data: bytes, as_char: bool = False, indent: str = "") -> str:
    if not data:
        return "{ 0 }"
    items = []
    for b in data:
        if as_char and b >= 0x80:
            items.append(f"(char)0x{b:02X}")
        else:
            items.append(f"0x{b:02X}")
    lines = [", ".join(items[i:i + 12]) for i in range(0, len(items), 12)]
    if len(lines) == 1:
        return "{ " + lines[0] + " }"
    return "{\n" + ",\n".join(indent + "    " + ln for ln in lines) + "\n" + indent + "}"


def c_value(f: Field, v) -> str:
    if f.kind == "scalar":
        return c_int(f.base, v)
    if f.kind == "bytes":
        return c_byte_list(bytes.fromhex(v))
    if f.kind == "str":
        return c_byte_list(v.encode("utf-8"), as_char=True)
    return c_struct_init(f.struct, v)


def c_struct_init(st: Struct, value: dict) -> str:
    parts = [f".{f.name} = {c_value(f, value[f.name])}" for f in st.fields if not f.tail]
    return "{ " + ", ".join(parts) + " }"


def gen_c_golden(model: dict, cases: list[dict]) -> str:
    o = [
        "/*",
        " * golden_cases.h",
        " *",
        f" * {BANNER}",
        " *",
        " * The examples of host_protocol.toml as C structs, with the bytes the reference",
        " * packer in gen_protocol.py computed for them. test/host_protocol checks that",
        " * the firmware's structs and frame_codec produce exactly these bytes; the web",
        " * app's tests check golden.json against the same bytes.",
        " */",
        "",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "host_protocol.h"',
        "",
        "typedef struct {",
        "    const char    *name;",
        "    const uint8_t *raw;",
        "    uint16_t       rawLen;",
        "    uint16_t       crc;",
        "    const uint8_t *wire;",
        "    uint16_t       wireLen;",
        "} goldenCodecCase_t;",
        "",
        "typedef struct {",
        "    const char    *name;",
        "    hpHeader_t     header;",
        "    const void    *fixed;     /* the C struct (or the status alone)          */",
        "    uint16_t       fixedLen;",
        "    const void    *tail;      /* tail items, laid out as C sees them, or NULL */",
        "    uint16_t       tailLen;",
        "    const uint8_t *payload;   /* expected payload bytes                       */",
        "    uint16_t       payloadLen;",
        "    const uint8_t *wire;      /* expected frame on the wire, delimiter included */",
        "    uint16_t       wireLen;",
        "} goldenMsgCase_t;",
        "",
        "/* ---- frame_codec vectors ---------------------------------------------- */",
        "",
    ]
    for i, (name, raw) in enumerate(CODEC_VECTORS):
        o.append(f"static const uint8_t goldenCodec{i}Raw[] = {c_byte_list(raw)};")
        o.append(f"static const uint8_t goldenCodec{i}Wire[] = {c_byte_list(frame_encode(raw))};")
    o += ["", "static const goldenCodecCase_t goldenCodecCases[] = {"]
    for i, (name, raw) in enumerate(CODEC_VECTORS):
        o.append(f'    {{ "{name}", goldenCodec{i}Raw, {len(raw)}U, 0x{crc16(raw):04X}U, '
                 f"goldenCodec{i}Wire, {len(frame_encode(raw))}U }},")
    o += ["};", "#define GOLDEN_CODEC_COUNT (sizeof(goldenCodecCases) / sizeof(goldenCodecCases[0]))", "",
          "/* ---- message examples ------------------------------------------------- */", ""]

    rows = []
    for c in cases:
        st, value, n = c["struct"], c["value"], "golden" + c["cname"]
        o.append(f"/* {c['name']} */")
        if is_status_only(st, value):
            o.append(f"static const int16_t {n}Fixed = {value['status']};")
            fixed, fixed_len = f"&{n}Fixed", "sizeof(int16_t)"
        elif st.fields and any(not f.tail for f in st.fields):
            o.append(f"static const {st.c_type} {n}Fixed = {c_struct_init(st, value)};")
            fixed, fixed_len = f"&{n}Fixed", f"{st.macro}_BYTES"
        else:
            fixed, fixed_len = "NULL", "0U"

        tail, tail_len = "NULL", "0U"
        t = st.tail
        if t is not None and not is_status_only(st, value):
            tv = value[t.name]
            if len(tv) > 0:
                if t.kind == "struct":
                    items = ",\n".join("    " + c_struct_init(t.struct, x) for x in tv)
                    o.append(f"static const {t.struct.c_type} {n}Tail[] = {{\n{items}\n}};")
                elif t.kind == "scalar":
                    items = ", ".join(c_int(t.base, x) for x in tv)
                    o.append(f"static const {SCALARS[t.base][2]} {n}Tail[] = {{ {items} }};")
                elif t.kind == "str":
                    o.append(f"static const char {n}Tail[] = {c_byte_list(tv.encode('utf-8'), as_char=True)};")
                else:
                    o.append(f"static const uint8_t {n}Tail[] = {c_byte_list(bytes.fromhex(tv))};")
                tail, tail_len = f"{n}Tail", f"sizeof({n}Tail)"
        payload = c["payload"]
        if payload:
            o.append(f"static const uint8_t {n}Payload[] = {c_byte_list(payload)};")
        o.append(f"static const uint8_t {n}Wire[] = {c_byte_list(c['wire'])};")
        o.append("")
        h = c["header"]
        rows.append(
            f'    {{ "{c["name"]}", {{ .msgId = 0x{h["msgId"]:02X}U, .flags = 0x{h["flags"]:02X}U, '
            f'.tag = 0x{h["tag"]:04X}U }},\n'
            f"      {fixed}, {fixed_len}, {tail}, {tail_len},\n"
            f"      {n + 'Payload' if payload else 'NULL'}, {len(payload)}U, {n}Wire, {len(c['wire'])}U }},")
    o += ["static const goldenMsgCase_t goldenMsgCases[] = {"] + rows + [
        "};", "#define GOLDEN_MSG_COUNT (sizeof(goldenMsgCases) / sizeof(goldenMsgCases[0]))", ""]
    return "\n".join(o)


