#!/usr/bin/env python3
"""
TimeTaker host protocol generator.

Reads protocol/host_protocol.toml (the protocol) and writes:

  ControlModule/.../app/config/host_protocol.h          C: IDs, enums, status codes, packed structs
  ControlModule/.../test/host_protocol/golden_cases.h   C: the TOML examples as structs + expected bytes
  WebApp/src/protocol/generated.ts                      TS: descriptors, types, encode/decode wrappers
  protocol/golden/golden.json                           TS tests: the same examples + codec vectors

    python3 protocol/gen_protocol.py           regenerate
    python3 protocol/gen_protocol.py --check   exit 1 if an output is stale (the host tests run this)

Standard library only (tomllib needs Python 3.11+).

This file is also the third implementation of the wire format. Its packer,
CRC and COBS encoder compute the golden bytes. The C test holds the
firmware's structs and frame_codec to them, and the TS test does the same for
the web app. Three independent implementations that agree byte for byte are
the cross-language check. The COBS encoder must therefore stay the same
algorithm as frame_codec.c and codec.ts: a 0xFF block is always followed by a
new block, even at the end of the data.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
CTRL = ROOT / "ControlModule" / "SideModuleFirmware" / "LapCounterControlModule_cmake"
SCHEMA = HERE / "host_protocol.toml"

OUT_C_HEADER = CTRL / "app" / "config" / "host_protocol.h"
OUT_C_GOLDEN = CTRL / "test" / "host_protocol" / "golden_cases.h"
OUT_TS = ROOT / "WebApp" / "src" / "protocol" / "generated.ts"
OUT_JSON = HERE / "golden" / "golden.json"

HEADER_BYTES = 4
CRC_BYTES = 2

# Event and response fields every message of that kind starts with.
INJECTED_STATUS = {"name": "status", "type": "i16",
                   "doc": "ctrlStatus_e. On error the payload is this field only."}
INJECTED_EVSEQ = {"name": "evSeq", "type": "u32",
                  "doc": "Event sequence number within this boot (bootId)"}

SCALARS = {  # name: (bytes, signed, C type)
    "u8": (1, False, "uint8_t"), "i8": (1, True, "int8_t"),
    "u16": (2, False, "uint16_t"), "i16": (2, True, "int16_t"),
    "u32": (4, False, "uint32_t"), "i32": (4, True, "int32_t"),
    "u64": (8, False, "uint64_t"), "i64": (8, True, "int64_t"),
}

KIND_RANGES = {  # message kind: allowed id range (inclusive)
    "request": (0x00, 0xBF),
    "event": (0xC0, 0xDF),
    "stream": (0xE0, 0xFF),
}

BANNER = "GENERATED by protocol/gen_protocol.py from protocol/host_protocol.toml. Do not edit."


class SchemaError(Exception):
    pass


# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------

@dataclass
class Field:
    name: str
    kind: str                 # "scalar" | "bytes" | "str" | "struct"
    base: str                 # scalar type, or struct name for kind "struct"
    count: int | None         # N for fixed bytes/str
    tail: bool
    enum: str | None
    doc: str
    struct: "Struct | None" = None
    injected: bool = False

    @property
    def size(self) -> int:
        """Fixed bytes this field occupies; 0 for a tail."""
        if self.tail:
            return 0
        if self.kind == "scalar":
            return SCALARS[self.base][0]
        if self.kind in ("bytes", "str"):
            return self.count
        return self.struct.size

    @property
    def item_size(self) -> int:
        """Bytes per tail element."""
        if self.kind == "scalar":
            return SCALARS[self.base][0]
        if self.kind in ("bytes", "str"):
            return 1
        return self.struct.size


@dataclass
class Struct:
    name: str                 # TS type name: "HelloReq", "NodeInfo"
    fields: list[Field]
    doc: str = ""
    is_response: bool = False

    @property
    def c_type(self) -> str:
        return f"hp{self.name}_t"

    @property
    def macro(self) -> str:
        return "HP_" + upper_snake(self.name)

    @property
    def ts_const(self) -> str:
        return upper_snake(self.name)

    @property
    def size(self) -> int:
        return sum(f.size for f in self.fields)

    @property
    def tail(self) -> Field | None:
        return self.fields[-1] if self.fields and self.fields[-1].tail else None


@dataclass
class Message:
    id: int
    name: str                 # "HELLO"
    kind: str
    doc: str
    req: Struct | None = None
    rsp: Struct | None = None
    body: Struct | None = None
    examples: dict | None = None   # part -> example value


def camel(upper: str) -> str:
    return "".join(p.capitalize() for p in upper.lower().split("_"))


def upper_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def cap_first(name: str) -> str:
    return name[0].upper() + name[1:]


# ---------------------------------------------------------------------------
# Loading and validation
# ---------------------------------------------------------------------------

TYPE_RE = re.compile(r"^(?P<base>[A-Za-z_][A-Za-z0-9_]*)(?P<arr>\[(?P<n>\d*)\])?$")


def parse_field(raw: dict, structs: dict[str, Struct], enums: dict, where: str,
                injected: bool = False) -> Field:
    for key in ("name", "type"):
        if key not in raw:
            raise SchemaError(f"{where}: field without '{key}'")
    unknown = set(raw) - {"name", "type", "enum", "doc"}
    if unknown:
        raise SchemaError(f"{where}.{raw['name']}: unknown keys {sorted(unknown)}")
    m = TYPE_RE.match(raw["type"])
    if not m:
        raise SchemaError(f"{where}.{raw['name']}: bad type '{raw['type']}'")
    base, arr, n = m.group("base"), m.group("arr"), m.group("n")
    tail = arr is not None and n == ""
    count = int(n) if arr is not None and n != "" else None
    if count is not None and count == 0:
        raise SchemaError(f"{where}.{raw['name']}: zero-length array")

    if base in SCALARS:
        if count is not None and base != "u8":
            raise SchemaError(f"{where}.{raw['name']}: fixed arrays are u8[N] only")
        if count is not None or (tail and base == "u8"):
            kind = "bytes"
        else:
            kind = "scalar"
    elif base == "str":
        if arr is None:
            raise SchemaError(f"{where}.{raw['name']}: str needs [N] or []")
        kind = "str"
    elif base in structs:
        if count is not None:
            raise SchemaError(f"{where}.{raw['name']}: fixed struct arrays are not supported")
        kind = "struct"
    else:
        raise SchemaError(f"{where}.{raw['name']}: unknown type '{base}'")

    enum = raw.get("enum")
    if enum is not None and enum not in enums:
        raise SchemaError(f"{where}.{raw['name']}: unknown enum '{enum}'")
    return Field(name=raw["name"], kind=kind, base=base, count=count, tail=tail, enum=enum,
                 doc=raw.get("doc", ""), struct=structs.get(base), injected=injected)


def build_struct(name: str, raw_fields: list, structs: dict, enums: dict, where: str,
                 inject: dict | None = None, doc: str = "", is_response: bool = False) -> Struct:
    fields = []
    if inject is not None:
        fields.append(parse_field(inject, structs, enums, where, injected=True))
    fields += [parse_field(f, structs, enums, where) for f in raw_fields]
    names = [f.name for f in fields]
    dupes = {n for n in names if names.count(n) > 1}
    if dupes:
        raise SchemaError(f"{where}: duplicate fields {sorted(dupes)}")
    for f in fields[:-1]:
        if f.tail:
            raise SchemaError(f"{where}.{f.name}: only the last field may be a tail")
    st = Struct(name=name, fields=fields, doc=doc, is_response=is_response)
    if st.tail is not None and len(fields) == 1:
        raise SchemaError(f"{where}: a struct needs a fixed field before its tail")
    return st


def load(path: Path) -> dict:
    with path.open("rb") as fh:
        doc = tomllib.load(fh)

    proto = doc["protocol"]
    max_payload = proto["max_payload"]
    max_event = proto["max_event_payload"]

    flags = doc.get("flag", [])
    statuses = doc.get("status", [])
    if not any(s["name"] == "OK" and s["value"] == 0 for s in statuses):
        raise SchemaError("status: OK = 0 is required")
    for s in statuses:
        if s["name"] != "OK" and s["value"] >= 0:
            raise SchemaError(f"status {s['name']}: errors must be negative")
    check_unique([s["name"] for s in statuses], "status names")
    check_unique([s["value"] for s in statuses], "status values")

    enums = {}
    for e in doc.get("enum", []):
        check_unique([v["name"] for v in e["values"]], f"enum {e['name']} names")
        check_unique([v["value"] for v in e["values"]], f"enum {e['name']} values")
        enums[e["name"]] = e

    structs: dict[str, Struct] = {}
    header = build_struct("Header", [
        {"name": "msgId", "type": "u8", "doc": "Message id"},
        {"name": "flags", "type": "u8", "doc": "HP_FLAG_* bits"},
        {"name": "tag", "type": "u16", "doc": "Request id (requests and responses), 0 otherwise"},
    ], structs, enums, "header")
    if header.size != HEADER_BYTES:
        raise SchemaError("header size changed")

    for s in doc.get("struct", []):
        name = cap_first(s["name"])
        if s["name"] in structs:
            raise SchemaError(f"struct {s['name']} defined twice")
        st = build_struct(name, s["fields"], structs, enums, f"struct {s['name']}", doc=s.get("doc", ""))
        if st.tail is not None:
            raise SchemaError(f"struct {s['name']}: reusable structs cannot have a tail")
        structs[s["name"]] = st

    messages = []
    for m in doc.get("message", []):
        mid, name, kind = m["id"], m["name"], m["kind"]
        where = f"message {name}"
        if kind not in KIND_RANGES:
            raise SchemaError(f"{where}: unknown kind '{kind}'")
        lo, hi = KIND_RANGES[kind]
        if not lo <= mid <= hi:
            raise SchemaError(f"{where}: id 0x{mid:02X} outside the {kind} range 0x{lo:02X}-0x{hi:02X}")
        base = camel(name)
        msg = Message(id=mid, name=name, kind=kind, doc=m.get("doc", ""), examples={})
        if kind == "request":
            msg.req = build_struct(base + "Req", m.get("request", []), structs, enums, where + ".request")
            msg.rsp = build_struct(base + "Rsp", m.get("response", []), structs, enums, where + ".response",
                                   inject=INJECTED_STATUS, is_response=True)
            parts = (("request", msg.req), ("response", msg.rsp))
            for part, _ in parts:
                if f"example_{part}" in m:
                    msg.examples[part] = m[f"example_{part}"]
        else:
            inject = INJECTED_EVSEQ if kind == "event" else None
            msg.body = build_struct(base, m.get("fields", []), structs, enums, where, inject=inject)
            parts = (("body", msg.body),)
            if "example" in m:
                msg.examples["body"] = m["example"]
        if kind == "event" and msg.body.size > max_event:
            raise SchemaError(f"{where}: {msg.body.size} B, over max_event_payload {max_event} "
                              "(the control module's event log slot)")
        for _, st in parts:
            if st.size > max_payload:
                raise SchemaError(f"{where}: {st.name} is {st.size} B, over max_payload {max_payload}")
            if st.tail is not None and st.size + st.tail.item_size > max_payload:
                raise SchemaError(f"{where}: {st.name} has no room for a single tail item")
        messages.append(msg)

    check_unique([m.id for m in messages], "message ids")
    check_unique([m.name for m in messages], "message names")
    messages.sort(key=lambda m: m.id)

    usb = doc.get("usb")
    if usb is None or not all(k in usb for k in ("vid", "pid", "product", "pid_boot", "product_boot")):
        raise SchemaError("[usb] needs vid, pid, product, pid_boot and product_boot")

    return {"proto": proto, "usb": usb, "flags": flags, "statuses": statuses, "enums": enums,
            "header": header, "structs": structs, "messages": messages}


def check_unique(items: list, what: str) -> None:
    seen, dupes = set(), set()
    for i in items:
        (dupes if i in seen else seen).add(i)
    if dupes:
        raise SchemaError(f"duplicate {what}: {sorted(dupes, key=str)}")


# ---------------------------------------------------------------------------
# Reference wire implementation (computes the golden bytes)
# ---------------------------------------------------------------------------

def crc16(data: bytes) -> int:
    """CRC-16/CCITT-FALSE: poly 0x1021, init 0xFFFF, no reflection, no xorout."""
    crc = 0xFFFF
    for b in data:
        crc ^= b << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def frame_encode(raw: bytes) -> bytes:
    """COBS(raw | crc16 LE) + 0x00, the same algorithm as frame_codec.c."""
    crc = crc16(raw)
    data = raw + bytes((crc & 0xFF, crc >> 8))
    out = bytearray([0])
    code_idx, code = 0, 1
    for b in data:
        if b == 0:
            out[code_idx] = code
            code_idx, code = len(out), 1
            out.append(0)
        else:
            out.append(b)
            code += 1
            if code == 0xFF:
                out[code_idx] = code
                code_idx, code = len(out), 1
                out.append(0)
    out[code_idx] = code
    out.append(0)
    return bytes(out)


def pack_scalar(base: str, v, where: str) -> bytes:
    size, signed, _ = SCALARS[base]
    if not isinstance(v, int) or isinstance(v, bool):
        raise SchemaError(f"{where}: expected an integer, got {v!r}")
    try:
        return v.to_bytes(size, "little", signed=signed)
    except OverflowError:
        raise SchemaError(f"{where}: {v} does not fit {base}") from None


def hex_bytes(v, where: str) -> bytes:
    if not isinstance(v, str):
        raise SchemaError(f"{where}: bytes are given as a hex string")
    try:
        return bytes.fromhex(v)
    except ValueError:
        raise SchemaError(f"{where}: bad hex string") from None


def pack_field(f: Field, v, where: str) -> bytes:
    where = f"{where}.{f.name}"
    if f.tail:
        if f.kind == "bytes":
            return hex_bytes(v, where)
        if f.kind == "str":
            return v.encode("utf-8")
        if not isinstance(v, list):
            raise SchemaError(f"{where}: tail needs a list")
        if f.kind == "scalar":
            return b"".join(pack_scalar(f.base, x, f"{where}[{i}]") for i, x in enumerate(v))
        return b"".join(pack_struct(f.struct, x, f"{where}[{i}]") for i, x in enumerate(v))
    if f.kind == "scalar":
        return pack_scalar(f.base, v, where)
    if f.kind == "bytes":
        b = hex_bytes(v, where)
        if len(b) != f.count:
            raise SchemaError(f"{where}: needs exactly {f.count} bytes, got {len(b)}")
        return b
    if f.kind == "str":
        b = v.encode("utf-8")
        if len(b) > f.count:
            raise SchemaError(f"{where}: {len(b)} UTF-8 bytes do not fit str[{f.count}]")
        return b + bytes(f.count - len(b))
    return pack_struct(f.struct, v, where)


def is_status_only(st: Struct, value: dict) -> bool:
    return st.is_response and value.get("status", 0) != 0


def pack_struct(st: Struct, value: dict, where: str) -> bytes:
    if not isinstance(value, dict):
        raise SchemaError(f"{where}: expected a table")
    value = with_defaults(st, value)
    if is_status_only(st, value):
        extra = set(value) - {"status"}
        if extra:
            raise SchemaError(f"{where}: an error response carries the status only, not {sorted(extra)}")
        return pack_scalar("i16", value["status"], where + ".status")
    names = {f.name for f in st.fields}
    unknown = set(value) - names
    missing = names - set(value)
    if unknown:
        raise SchemaError(f"{where}: unknown fields {sorted(unknown)}")
    if missing:
        raise SchemaError(f"{where}: missing fields {sorted(missing)}")
    out = b"".join(pack_field(f, value[f.name], where) for f in st.fields)
    if st.tail is not None and (len(out) - st.size) % st.tail.item_size:
        raise SchemaError(f"{where}: tail length is not a whole number of items")
    return out


def with_defaults(st: Struct, value: dict) -> dict:
    """Injected fields (status, evSeq) default to 0 in examples."""
    value = dict(value)
    for f in st.fields:
        if f.injected:
            value.setdefault(f.name, 0)
    return value


def json_value(f: Field, v):
    """Example value in the JSON form the TS test compares against."""
    if f.tail:
        if f.kind == "bytes":
            return v.lower()
        if f.kind == "str":
            return v
        if f.kind == "scalar":
            return [x if SCALARS[f.base][0] <= 4 else str(x) for x in v]
        return [json_struct(f.struct, x) for x in v]
    if f.kind == "scalar":
        return v if SCALARS[f.base][0] <= 4 else str(v)
    if f.kind == "bytes":
        return v.lower()
    if f.kind == "str":
        return v
    return json_struct(f.struct, v)


def json_struct(st: Struct, value: dict) -> dict:
    value = with_defaults(st, value)
    if is_status_only(st, value):
        return {"status": value["status"]}
    return {f.name: json_value(f, value[f.name]) for f in st.fields}


