def gen_json(model: dict, cases: list[dict]) -> str:
    doc = {
        "generatedFrom": "protocol/host_protocol.toml",
        "note": BANNER,
        "protocol": {"major": model["proto"]["major"], "minor": model["proto"]["minor"]},
        "codec": [{"name": n, "raw": r.hex(), "crc": crc16(r), "wire": frame_encode(r).hex()}
                  for n, r in CODEC_VECTORS],
        "messages": [{
            "name": c["name"],
            "struct": c["struct"].name,
            "header": c["header"],
            "statusOnly": is_status_only(c["struct"], c["value"]),
            "value": json_struct(c["struct"], c["value"]),
            "payload": c["payload"].hex(),
            "wire": c["wire"].hex(),
        } for c in cases],
    }
    return json.dumps(doc, indent=2, ensure_ascii=False) + "\n"


