/******************************************************************************/
/* Exported functions for PWR in HAL layer */
/******************************************************************************/

system_status_t mx_pwr_init(void)
{
  hal_pwr_wakeup_pin_config_t wkup_config;

  /****************************************************************************/
  /* Wakeup Pins Configurations                                               */
  /****************************************************************************/
  /* Configuration of selected Wakeup pins with pull NO and LOW polarity */
  wkup_config.polarity = HAL_PWR_WAKEUP_PIN_POLARITY_LOW;
  wkup_config.pull     = HAL_PWR_WAKEUP_PIN_PULL_NO;

  if (HAL_PWR_LP_SetConfigWakeupPin(HAL_PWR_WAKEUP_PIN_1, &wkup_config) != HAL_OK)
  {
    return SYSTEM_POWER_ERROR;
  }

  /****************************************************************************/
  /* Enable all configured Wakeup Pins                                        */
  /****************************************************************************/
  HAL_PWR_LP_EnableWakeupPin(HAL_PWR_WAKEUP_PIN_1);

  /****************************************************************************/
  /* Configuration of I/O retention in standby mode                           */
  /****************************************************************************/
  /* Enable I/O retention mode for all I/Os except standby I/Os and PA13, PA14, PA15, PB4 pins */
  HAL_PWR_LP_EnableIORetention(HAL_PWR_IO_RETENTION_GPIO);

  return SYSTEM_OK;
}

system_status_t mx_pwr_deinit(void)
{
  /****************************************************************************/
  /* Disable all configured Wakeup Pins                                       */
  /****************************************************************************/
  HAL_PWR_LP_DisableWakeupPin(HAL_PWR_WAKEUP_PIN_1);

  return SYSTEM_OK;
}

/******************************************************************************/
/* Runtime APIs                                                               */
/******************************************************************************/
system_status_t mx_pwr_enter_low_power(void)
{
  /* Clear both standby and stop flags */
  HAL_PWR_CleanPreviousSystemPowerMode();

  /* Enter the MCU in stop mode */
  HAL_PWR_EnterStopMode(HAL_PWR_LOW_PWR_MODE_WFI, HAL_PWR_STOP1_MODE);

  return SYSTEM_OK;
}

system_status_t mx_pwr_exit_low_power(void)
{
  /* This API is the runtime API generated by RCC module */
  return (mx_rcc_init());
}
